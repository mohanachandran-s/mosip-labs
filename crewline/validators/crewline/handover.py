"""`crewline resume [<task>]`: everything a new session needs, generated from the task's own records.

  TSK-009  hand-over written to <task>/HANDOVER.md and printed; the task becomes the active one     INFO
  TSK-001  no such task                                                                              BLOCK

Generated, never hand-written: the manifest stays the source of truth, so a stale file is regenerated by running it again.
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

from . import manifest, task, workspace
from .gitio import head
from .result import BLOCK, INFO, Result

CAP = 3


def _agents_for(state: str) -> list[str]:
    out = []
    for p in sorted((manifest.CORE / "agents").rglob("*.md")):
        text = p.read_text(encoding="utf-8")[:600]
        m = re.search(r'^workflow_states:\s*"?([^"\n]+)', text, re.M)
        n = re.search(r"^name:\s*(\S+)", text, re.M)
        if m and n and n.group(1) != "orchestrator" and state in re.split(r"[,\s]+", m.group(1)):
            out.append(n.group(1))
    return out


def _usage(task_dir: Path) -> list[str]:
    try:
        data = json.loads((task_dir / "usage.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ["- not metered yet: `crewline usage --manifest <m> --transcript <session.jsonl>`"]
    budget = data.get("budget") or {}
    lines = [f"- task: {(data.get('overall') or {}).get('total', 0):,} of {budget.get('per_task', 'no cap'):,} tokens"
             if isinstance(budget.get("per_task"), int)
             else f"- task: {(data.get('overall') or {}).get('total', 0):,} tokens"]
    stages = sorted((data.get("by_stage") or {}).items(), key=lambda kv: -(kv[1] or {}).get("total", 0))[:5]
    lines += [f"- {name}: {(row or {}).get('total', 0):,}" for name, row in stages]
    return lines


def _stale(doc: dict, commit: str) -> list[str]:
    return [g["gate"] for g in doc.get("gates", []) if g.get("status") == "PASS" and g.get("checked_at_commit")
            and commit and g["checked_at_commit"] != commit]


def build(path: Path, doc: dict) -> str:
    tid, state, resume = doc.get("task_id", path.parent.name), doc.get("current_state"), doc.get("resume_state")
    nxt = resume if state in ("WAITING_FOR_USER", "S_ESCALATE") else task._next_state(doc)
    check = manifest.transition(str(path), nxt) if nxt else None
    others = [n for n in manifest.Ctx(doc).next_states(state or "") if n != nxt] if state not in ("WAITING_FOR_USER", "S_ESCALATE") else []
    repos = (doc.get("scope") or {}).get("repositories") or []
    trees = [w for w in (doc.get("workspace") or {}).get("worktrees") or [] if not w.get("removed_at")]
    tree = next((w.get("path") for w in trees if w.get("purpose") == "task"), "") or next(
        (r.get("path") for r in manifest.changed_repos(doc) if r.get("path")), "")
    commit = ""
    if tree and Path(tree).is_dir():
        try:
            commit = head(tree)
        except RuntimeError:
            pass
    rep = doc.get("repair") or {}
    t = doc.get("tracker") or {}
    open_gates = [f"{g.get('gate')} {g.get('status')}" for g in doc.get("gates", []) if g.get("status") not in ("PASS", "NOT_APPLICABLE")]
    unused = [a.get("action") for a in doc.get("approvals", []) if not a.get("consumed_by")]
    defects = [f"{d.get('id', '?')} {d.get('class', '')} {d.get('status', '')}" for d in doc.get("defects", [])
               if d.get("status") in ("open", "raised")]
    pr = doc.get("pr") or {}
    say = [
        f"# {tid} hand-over",
        f"Generated by `crewline resume` at {datetime.now(timezone.utc):%Y-%m-%dT%H:%M:%SZ}, from the manifest. Do not edit; run it again.",
        "",
        "## Where the task is",
        f"- {doc.get('task_type')} / {doc.get('risk_tier')} / {doc.get('outcome')}; Crewline {doc.get('crewline_version', '?')}",
        f"- State: **{state}**" + (f", resumes to **{resume}**" if resume else "") + (f"; next: **{nxt}**" if nxt else "; no next state")
        + (f" (also legal: {', '.join(others)})" if others else ""),
        f"- Manifest: `{path}`",
        f"- Ticket: " + (f"{t.get('system')} {t.get('key')} {t.get('url', '')}".strip() if t.get("key")
                         else f"waived ({t['waived'].get('reason')})" if t.get("waived") else "none yet (MAN-017)")
        + f"; subtasks: {len(t.get('subtasks') or [])}",
        f"- Repair: SDET {rep.get('attempt_count', 0)} of {CAP}, developer {rep.get('dev_attempt_count', 0)} of {CAP}"
        + (f"; last class {rep['classification']}" if rep.get("classification") else ""),
        f"- Reviews: implementation {(doc.get('reviews') or {}).get('implementation_review', '?')}, "
        f"fresh-context {(doc.get('reviews') or {}).get('fresh_context_review', '?')}",
    ]
    if pr.get("url"):
        say.append(f"- PR: {pr['url']}; CI {pr.get('ci_status', '?')}, valid comments open {pr.get('valid_comments_open', 0)}, "
                   f"unresolved threads {pr.get('unresolved_threads', 0)}")
    for r in repos:
        say.append(f"- Repository {r.get('name', '?')}: `{r.get('path', '')}` branch {r.get('branch', '?')}, base "
                   f"{r.get('upstream_repo', '')}:{r.get('base_branch', '')} {str(r.get('baseline_commit') or '')[:10]}")
    say += ["", "## What is open"]
    blocks = [f for f in check.findings if f.severity == BLOCK and not f.approved_by] if check else []
    say += [f"- {f.rule_id}: {f.message}" for f in blocks] or [f"- nothing blocks the move to {nxt}" if nxt else "- nothing"]
    if open_gates:
        say.append(f"- gates not PASS: {', '.join(open_gates)}")
    stale = _stale(doc, commit)
    if stale:
        say.append(f"- PASS on another commit than HEAD {commit[:10]}: {', '.join(stale)}")
    if defects:
        say.append(f"- defects: {'; '.join(defects)}")
    if unused:
        say.append(f"- approvals not used yet: {', '.join(unused)}")
    if doc.get("residual_risks"):
        say.append(f"- residual risks: {'; '.join(map(str, doc['residual_risks']))}")
    say += ["", "## Token use"] + _usage(path.parent)
    say += ["", "## Next"]
    if tree:
        say.append(f"1. Open the session in `{tree}` (it finds its own task; `crewline task worktree --id {tid}` if the folder or plugin enable is missing).")
    else:
        say.append(f"1. No worktree yet: `crewline task worktree --id {tid} --base <upstream ref> --branch <name>` after approval `base_branch`.")
    work = resume if state in ("WAITING_FOR_USER", "S_ESCALATE") else state
    agents = _agents_for(work or "")
    packet = path.parent / "packets" / f"{work}.md"
    say.append(f"2. Re-check gates: `crewline gates refresh --id {tid}` (`--all` after a code change, `--rerun` to run recorded builds and tests again).")
    say.append(f"3. Work {work}" + (f" with {', '.join(agents)}" if agents else "") + (f"; packet `{packet}`." if packet.is_file() else "."))
    if nxt:
        say.append(f"4. `crewline manifest {path} --to {nxt}`, and with exit 0 `--apply`.")
    say.append("Ask the user before every commit, push, PR and bug; approvals are single-use. Do not re-read core or earlier packets.")
    return "\n".join(say) + "\n"


def run(task_id: str | None, cwd: str | None = None) -> Result:
    res = Result("resume", inputs={"task": task_id or ""})
    if task_id:
        path, doc, err = task._load(task_id)
    else:
        path = workspace.active_manifest(cwd=cwd)[0]
        err = "no active task: pass <task>"
        doc = json.loads(path.read_text(encoding="utf-8")) if path else None
    if doc is None:
        res.add("TSK-001", BLOCK, err)
        return res.finish()
    text = build(path, doc)
    out = path.parent / "HANDOVER.md"
    out.write_text(text, encoding="utf-8")
    workspace.active_file().write_text(path.parent.name + "\n", encoding="utf-8")
    res.inputs.update(manifest=str(path), handover=str(out))
    res.add("TSK-009", INFO, f"{path.parent.name} is now the active task; hand-over at {out}\n\n{text}")
    return res.finish()
